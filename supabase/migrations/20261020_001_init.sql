create or replace view public.v_vetmo_meta as
select
    m.patch_id,
    p.version as patch_version,
    m.hero_id,
    h.localized_name as name,
    h.name as internal_name,
    h.icon_url,
    h.primary_attr,
    h.attack_type,
    m.rank_tier,
    m.position,
    m.window_days,
    m.match_count,
    m.win_count,
    m.win_rate,
    m.pick_rate,
    m.ban_rate,
    m.pick_share,
    m.is_popular,
    m.delta_win,
    m.delta_pick,
    m.delta_ban,
    m.ban_scope,
    m.updated_at
from public.vetmo_meta m
join public.vetmo_heroes h on h.id = m.hero_id
join public.vetmo_patches p on p.id = m.patch_id;

alter view public.v_vetmo_meta set (security_invoker = true);
grant select on public.v_vetmo_meta to anon, authenticated;

create or replace view public.v_vetmo_sync_status as
select id, started_at, finished_at, status, source, patch_version,
       rows_meta, rows_matchups, details, error
from public.vetmo_sync_runs
order by started_at desc
limit 1;

alter view public.v_vetmo_sync_status set (security_invoker = true);
grant select on public.v_vetmo_sync_status to anon, authenticated;

