-- VETMO 0.2 — Supabase schema
-- Apply in Supabase Dashboard -> SQL Editor -> New query.
-- All objects are prefixed vetmo_ to avoid collisions with existing tables.
-- Safe to re-run for the VETMO objects; it does not touch other public tables.

-- ---------------------------------------------------------------------------
-- Reference data
-- ---------------------------------------------------------------------------

create table if not exists public.vetmo_heroes (
    id              integer primary key,
    name            text not null unique,
    localized_name  text not null,
    primary_attr    text not null default '',
    attack_type     text not null default '',
    roles           jsonb not null default '[]'::jsonb,
    icon_url        text,
    is_validated    boolean not null default true,
    updated_at      timestamptz not null default now()
);

create table if not exists public.vetmo_patches (
    id               bigint generated by default as identity primary key,
    game_version_id  integer unique,
    version          text not null unique,
    release_date     date,
    is_current       boolean not null default false,
    source           text not null default 'stratz',
    created_at       timestamptz not null default now()
);

-- Current meta: one row per (patch, hero, rank, position, game mode, window).
-- rank_tier: 0 = all ranks, 1..8 = Herald..Immortal.
-- position:  0 = all positions, 1..5 = POSITION_1..POSITION_5.
-- window_days: 7 = latest available 7-day window, 0 = full historical patch.
create table if not exists public.vetmo_meta (
    patch_id     bigint not null references public.vetmo_patches(id) on delete cascade,
    hero_id      integer not null references public.vetmo_heroes(id) on delete cascade,
    rank_tier    smallint not null default 0 check (rank_tier between 0 and 8),
    position     smallint not null default 0 check (position between 0 and 5),
    game_mode    text not null default 'ALL_PICK_RANKED',
    window_days  smallint not null default 7 check (window_days in (0, 7)),
    match_count  integer not null default 0 check (match_count >= 0),
    win_count    integer not null default 0 check (win_count >= 0),
    win_rate     numeric(5,2) not null default 0 check (win_rate between 0 and 100),
    pick_rate    numeric(5,2) not null default 0 check (pick_rate between 0 and 100),
    ban_rate     numeric(5,2) check (ban_rate between 0 and 100),
    pick_share   numeric(5,2) check (pick_share between 0 and 100),
    is_popular   boolean not null default false,
    sample_reliable boolean not null default false,
    delta_win    numeric(5,2),
    delta_pick   numeric(5,2),
    delta_ban    numeric(5,2),
    ban_scope    text,
    source       text not null default 'stratz',
    updated_at   timestamptz not null default now(),
    primary key (patch_id, hero_id, rank_tier, position, game_mode, window_days)
);

-- Для проекта, где vetmo_meta уже создана предыдущей версией миграции.
alter table public.vetmo_meta
    add column if not exists sample_reliable boolean not null default false;

-- Daily snapshots for deltas and audit.
create table if not exists public.vetmo_snapshots (
    id            bigint generated by default as identity primary key,
    snapshot_date date not null,
    patch_id      bigint not null references public.vetmo_patches(id) on delete cascade,
    hero_id       integer not null references public.vetmo_heroes(id) on delete cascade,
    rank_tier     smallint not null default 0 check (rank_tier between 0 and 8),
    position      smallint not null default 0 check (position between 0 and 5),
    game_mode     text not null default 'ALL_PICK_RANKED',
    window_days   smallint not null default 7,
    match_count   integer not null default 0,
    win_count     integer not null default 0,
    win_rate      numeric(5,2) not null default 0,
    pick_rate     numeric(5,2) not null default 0,
    ban_rate      numeric(5,2),
    pick_share    numeric(5,2),
    is_popular    boolean not null default false,
    ban_scope     text,
    source        text not null default 'stratz',
    unique (snapshot_date, patch_id, hero_id, rank_tier, position, game_mode, window_days)
);

-- Для проекта, где vetmo_snapshots уже создана предыдущей версией миграции.
alter table public.vetmo_snapshots
    add column if not exists delta_win numeric(5,2),
    add column if not exists delta_pick numeric(5,2),
    add column if not exists delta_ban numeric(5,2),
    add column if not exists sample_reliable boolean not null default true;

create table if not exists public.vetmo_hero_matchups (
    patch_id      bigint not null references public.vetmo_patches(id) on delete cascade,
    hero_id       integer not null references public.vetmo_heroes(id) on delete cascade,
    vs_hero_id    integer not null references public.vetmo_heroes(id) on delete cascade,
    win_rate      numeric(5,2) not null default 0 check (win_rate between 0 and 100),
    match_count   integer not null default 0 check (match_count >= 0),
    source        text not null default 'stratz',
    updated_at    timestamptz not null default now(),
    primary key (patch_id, hero_id, vs_hero_id)
);

-- Агрегированная бан-статистика STRATZ banDay (одна строка на день × ранговую группу).
-- Примечание: STRATZ banDay игнорирует heroId, поэтому баны нельзя атрибутировать
-- конкретному герою. Таблица хранит общие бан-данныe по дню и ранговой группе.
create table if not exists public.vetmo_ban_stats (
    snapshot_date date not null,
    patch_id      bigint not null references public.vetmo_patches(id) on delete cascade,
    rank_tier     smallint not null default 0 check (rank_tier between 0 and 8),
    bracket       text not null,
    total_bans    integer not null default 0 check (total_bans >= 0),
    total_matches integer not null default 0 check (total_matches >= 0),
    ban_rate      numeric(5,2) check (ban_rate between 0 and 100),
    source        text not null default 'stratz',
    updated_at    timestamptz not null default now(),
    primary key (snapshot_date, patch_id, rank_tier, bracket)
);

create index if not exists vetmo_ban_stats_lookup_idx
    on public.vetmo_ban_stats (snapshot_date, rank_tier, bracket);

alter table public.vetmo_ban_stats enable row level security;
drop policy if exists vetmo_ban_stats_read on public.vetmo_ban_stats;
create policy vetmo_ban_stats_read on public.vetmo_ban_stats
    for select to anon, authenticated using (true);
grant select on public.vetmo_ban_stats to anon, authenticated;

create table if not exists public.vetmo_news (
    id           bigint generated by default as identity primary key,
    url          text not null unique,
    title        text not null,
    summary      text,
    published_at timestamptz,
    source       text not null default 'steam-rss',
    fetched_at   timestamptz not null default now()
);

-- ---------------------------------------------------------------------------
-- Per-user data (anonymous auth)
-- ---------------------------------------------------------------------------

create table if not exists public.vetmo_profiles (
    user_id        uuid primary key references auth.users(id) on delete cascade,
    overlay_x      integer not null default 20,
    overlay_y      integer not null default 20,
    opacity        numeric(3,2) not null default 0.85 check (opacity between 0 and 1),
    theme          text not null default 'dark' check (theme in ('dark', 'light')),
    click_through  boolean not null default false,
    show_dire      boolean not null default true,
    priorities     jsonb not null default '{}'::jsonb,
    display_index  integer not null default -1,
    updated_at     timestamptz not null default now()
);

-- Для проекта, где profiles уже создана предыдущей версией миграции.
alter table public.vetmo_profiles
    add column if not exists display_index integer not null default -1;

create table if not exists public.vetmo_drafts (
    id           bigint generated by default as identity primary key,
    user_id      uuid not null references auth.users(id) on delete cascade,
    started_at   timestamptz not null default now(),
    finished_at  timestamptz,
    current_step integer not null default 0,
    total_picks  integer not null default 10
);

create table if not exists public.vetmo_draft_picks (
    id         bigint generated by default as identity primary key,
    session_id bigint not null references public.vetmo_drafts(id) on delete cascade,
    team       text not null check (team in ('radiant', 'dire')),
    position   smallint not null check (position between 1 and 5),
    hero_id    integer not null references public.vetmo_heroes(id),
    step       smallint not null default 0,
    picked_at  timestamptz not null default now(),
    unique (session_id, team, position)
);

create table if not exists public.vetmo_sync_runs (
    id            bigint generated by default as identity primary key,
    started_at    timestamptz not null default now(),
    finished_at   timestamptz,
    status        text not null default 'running'
                  check (status in ('running', 'ok', 'partial', 'error')),
    source        text not null default 'stratz',
    patch_version text,
    rows_meta     integer not null default 0,
    rows_matchups integer not null default 0,
    details       jsonb not null default '{}'::jsonb,
    error         text
);

