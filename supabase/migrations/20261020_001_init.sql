    for select to anon, authenticated using (true);
create policy vetmo_meta_read on public.vetmo_meta
    for select to anon, authenticated using (true);
create policy vetmo_snapshots_read on public.vetmo_snapshots
    for select to anon, authenticated using (true);
create policy vetmo_matchups_read on public.vetmo_hero_matchups
    for select to anon, authenticated using (true);
create policy vetmo_news_read on public.vetmo_news
    for select to anon, authenticated using (true);
create policy vetmo_sync_runs_read on public.vetmo_sync_runs
    for select to anon, authenticated using (true);

create policy vetmo_profiles_own on public.vetmo_profiles
    for all to authenticated
    using (auth.uid() = user_id)
    with check (auth.uid() = user_id);

create policy vetmo_drafts_own on public.vetmo_drafts
    for all to authenticated
    using (auth.uid() = user_id)
    with check (auth.uid() = user_id);

create policy vetmo_draft_picks_own on public.vetmo_draft_picks
    for all to authenticated
    using (
        exists (
            select 1 from public.vetmo_drafts d
            where d.id = vetmo_draft_picks.session_id
              and d.user_id = auth.uid()
        )
    )
    with check (
        exists (
            select 1 from public.vetmo_drafts d
            where d.id = vetmo_draft_picks.session_id
              and d.user_id = auth.uid()
        )
    );

grant usage on schema public to anon, authenticated;
