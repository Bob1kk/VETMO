drop function if exists public.vetmo_get_meta_report(
    bigint, smallint, smallint, smallint, integer
);

create or replace function public.vetmo_get_meta_report(
    p_patch_id     bigint,
    p_rank_tier    smallint default 0,
    p_position     smallint default 0,
    p_window_days  smallint default 7,
    p_limit        integer default 200
)
returns table (
    hero_id          integer,
    name             text,
    internal_name    text,
    icon_url         text,
    primary_attr     text,
    attack_type      text,
    win_rate         numeric,
    delta_win        numeric,
    pick_rate        numeric,
    delta_pick       numeric,
    ban_rate         numeric,
    delta_ban        numeric,
    positions        smallint[],
    position_details jsonb,
    patch_version    text,
    match_count      integer,
    ban_scope        text
)
language sql
stable
security invoker
set search_path = public
as $$
    with chosen as (
        select m.*
        from public.vetmo_meta m
        where m.patch_id = p_patch_id
          and m.rank_tier = p_rank_tier
          and m.window_days = p_window_days
          and m.game_mode = 'ALL_PICK_RANKED'
          and (
              (p_position = 0 and m.position = 0)
              or (p_position > 0 and m.position = p_position and m.is_popular)
          )
    ),
    popular as (
        select
            m.hero_id,
            array_agg(m.position order by m.pick_share desc nulls last) as positions,
            jsonb_object_agg(
                m.position::text,
                jsonb_build_object(
                    'position', m.position,
                    'pick_share', m.pick_share,
                    'win_rate', m.win_rate,
                    'match_count', m.match_count
                )
            ) as position_details
        from public.vetmo_meta m
        where m.patch_id = p_patch_id
          and m.rank_tier = p_rank_tier
          and m.window_days = p_window_days
          and m.game_mode = 'ALL_PICK_RANKED'
          and m.position between 1 and 5
          and m.is_popular
        group by m.hero_id
    )
    select
        c.hero_id,
        h.localized_name,
        h.name,
        h.icon_url,
        h.primary_attr,
        h.attack_type,
        c.win_rate,
        c.delta_win,
        c.pick_rate,
        c.delta_pick,
        c.ban_rate,
        c.delta_ban,
        coalesce(pop.positions, '{}'::smallint[]),
        coalesce(pop.position_details, '{}'::jsonb),
        p.version,
        c.match_count,
        c.ban_scope
    from chosen c
    join public.vetmo_heroes h on h.id = c.hero_id
    join public.vetmo_patches p on p.id = c.patch_id
    left join popular pop on pop.hero_id = c.hero_id
    order by c.win_rate desc, c.pick_rate desc, h.localized_name
    limit greatest(0, p_limit);
$$;

grant execute on function public.vetmo_get_meta_report(
    bigint, smallint, smallint, smallint, integer
) to anon, authenticated;

-- Best-effort cleanup helper for cron / sync script.
create or replace function public.vetmo_prune_old_data(p_days integer default 90)
returns void
language sql
security definer
set search_path = public
as $$
    delete from public.vetmo_snapshots
    where snapshot_date < current_date - greatest(1, p_days);
$$;

revoke all on function public.vetmo_prune_old_data(integer) from public, anon, authenticated;
grant execute on function public.vetmo_prune_old_data(integer) to service_role;
